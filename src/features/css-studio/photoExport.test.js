import { expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { initialPreferences, updateProfile, resolveTheme } from "./theme";
import { themeArchive } from "./photoExport";
const catalog = JSON.parse(
  readFileSync(
    new URL("../../../public/css-studio/catalog.json", import.meta.url),
    "utf8",
  ),
);
function zipEntries(buffer) {
  const view = new DataView(buffer);
  const bytes = new Uint8Array(buffer);
  const entries = {};
  let at = 0;
  while (view.getUint32(at, true) === 0x04034b50) {
    const size = view.getUint32(at + 18, true),
      nameLength = view.getUint16(at + 26, true),
      extra = view.getUint16(at + 28, true);
    const name = new TextDecoder().decode(
      bytes.slice(at + 30, at + 30 + nameLength),
    );
    const start = at + 30 + nameLength + extra;
    entries[name] = bytes.slice(start, start + size);
    at = start + size;
  }
  return entries;
}
it("packages exact selected bytes with per-photo license and portable CSS AC-43/47", async () => {
  const p = updateProfile(initialPreferences(), { backgroundId: "spring-01" });
  const image = catalog.images[0];
  const bytes = readFileSync(
    new URL(
      "../../../public/css-studio/" + image.relativePath,
      import.meta.url,
    ),
  );
  const blob = await themeArchive(p, new Set(), catalog.images, async (url) => {
    expect(url).toBe("/css-studio/" + image.relativePath);
    return new Response(bytes, { headers: { "content-type": "image/webp" } });
  });
  const entries = zipEntries(await blob.arrayBuffer());
  expect(entries["css-studio/" + image.relativePath]).toEqual(
    new Uint8Array(bytes),
  );
  expect(JSON.parse(new TextDecoder().decode(entries["CREDITS.json"]))).toEqual(
    image,
  );
  const css = new TextDecoder().decode(entries["styles.css"]);
  for (const [key, value] of Object.entries(resolveTheme(p)))
    if (key !== "--studio-image") expect(css).toContain(`${key}: ${value};`);
  expect(css).toContain("./css-studio/" + image.relativePath);
});
it("rejects a corrupted selected download without packaging unrelated URLs", async () => {
  await expect(
    themeArchive(
      initialPreferences(),
      new Set(),
      catalog.images,
      async () =>
        new Response(new Uint8Array([0]), {
          headers: { "content-type": "image/webp" },
        }),
    ),
  ).rejects.toThrow("integrity");
});

it("exports generated bytes with portable CSS and metadata, excluding runtime URLs and prompts", async () => {
  const { createImageCache, memoryImageBackend } = await import("./imageCache");
  const images = createImageCache(memoryImageBackend(), {
    inspect: async () => ({ width: 1600, height: 1067 }),
  });
  const bytes = readFileSync(
    new URL(
      "../../../public/css-studio/images/spring/spring-01-woodland.webp",
      import.meta.url,
    ),
  );
  const image = await images.save({
    blob: new Blob([bytes], { type: "image/webp" }),
    context: {
      family: "seasons",
      id: "spring",
      mode: "light",
      contrast: false,
    },
  });
  const generatedImages = {
    [image.id]: {
      ...image,
      displayUrl: "blob:https://example.test/visit-only",
    },
  };
  const p = updateProfile(initialPreferences(), { backgroundId: image.id });
  const blob = await themeArchive(
    p,
    new Set(),
    [],
    () => {
      throw Error("No fetch expected");
    },
    { generatedImages, getGeneratedImage: (id) => images.get(id) },
  );
  const entries = zipEntries(await blob.arrayBuffer());
  const path = `css-studio/generated/${image.id}.webp`;
  expect(entries[path]).toEqual(new Uint8Array(bytes));
  expect(new TextDecoder().decode(entries["styles.css"])).toContain(
    `./${path}`,
  );
  const metadata = new TextDecoder().decode(entries["GENERATED_IMAGE.json"]);
  expect(metadata).toContain(image.sha256);
  expect(metadata).not.toMatch(/blob:|displayUrl|prompt|licenseUrl/);
  await expect(
    themeArchive(p, new Set(), [], undefined, {
      generatedImages,
      getGeneratedImage: async () => null,
    }),
  ).rejects.toThrow(/unavailable/i);
});
